	/**
	 * Remove the specified resource from storage.
	 *
	 * @param  int  $id
	 * @return \Illuminate\Http\Response
	 */
	public function destroy($id) {
		//
		$category = Category::find($id);
		$name = $category->name;
		$category->delete();
		return response()->json(compact('name'));
	}
}
